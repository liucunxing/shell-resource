            draft = {"expected_revision": 0, "rows": [{"dealerId": "D1", "amount": 100}]}
            await request("PUT", "initiatives/2/draft", json=draft)
            await request("POST", "initiatives/2/publish", json={"expected_revision": 1})
            await request("PUT", "initiatives/3/draft", status=404, json=draft)
            await request("PUT", "initiatives/4/draft", status=404, json=draft)
