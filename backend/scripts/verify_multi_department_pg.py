def require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


async def column_type(connection: AsyncConnection, schema: str) -> str:
    return await connection.scalar(
        text(
            "SELECT udt_name FROM information_schema.columns WHERE table_schema=:schema "
            "AND table_name='user_permissions' AND column_name='department'"
        ),
        {"schema": schema},
    )


async def migrate(connection: AsyncConnection, schema: str, direction: str) -> None:
    def execute(sync_connection):
        path = ROOT / "migrations/versions/20261014_01_user_department_array.py"
        spec = importlib.util.spec_from_file_location("department_migration_check", path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        operations = Operations(MigrationContext.configure(sync_connection))

        class IsolatedOperations:
            def execute(self, statement: str) -> None:
                require("data.user_permissions" in statement, "Unexpected migration target")
                operations.execute(
                    statement.replace("data.user_permissions", f"{schema}.user_permissions")
                )

        module.op = IsolatedOperations()
        getattr(module, direction)()

    await connection.run_sync(execute)


async def check_migration(connection: AsyncConnection, schema: str) -> list[str]:
    # LIKE excludes defaults, so the clone cannot consume any business sequences.
    await connection.execute(
        text(
            f"CREATE TABLE {schema}.user_permissions "
            "(LIKE data.user_permissions INCLUDING CONSTRAINTS INCLUDING INDEXES)"
        )
    )
    require(await column_type(connection, schema) == "varchar", "Expected legacy scalar schema")
    await connection.execute(
        text(
            f"ALTER TABLE {schema}.user_permissions "
            "ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY"
        )
    )
    for name in ("created_at", "updated_at"):
        await connection.execute(
            text(f"ALTER TABLE {schema}.user_permissions ALTER COLUMN {name} SET DEFAULT now()")
        )
    for number, role, department in [
        (1, "owner", " mkt "),
        (2, "admin", None),
        (3, "management", ""),
    ]:
        await connection.execute(
            text(
                f"INSERT INTO {schema}.user_permissions "
                "(id,email,display_name,role,department,sector,enabled) "
                "VALUES (:id,:email,'PG acceptance',:role,:department,"
                "CAST(:sector AS varchar[]),true)"
            ),
            {
                "id": number,
                "email": f"{role}@example.test",
                "role": role,
                "department": department,
                "sector": ["PCMO"] if role == "owner" else [],
            },
        )
    await migrate(connection, schema, "upgrade")
    rows = (
        await connection.execute(
            text(f"SELECT id,department FROM {schema}.user_permissions ORDER BY id")
        )
    ).all()
    require([row.department for row in rows] == [["MKT"], [], []], "Legacy conversion failed")
    require(await column_type(connection, schema) == "_varchar", "Expected varchar[]")
    await migrate(connection, schema, "downgrade")
    require(await column_type(connection, schema) == "varchar", "Singleton downgrade failed")
    await migrate(connection, schema, "upgrade")
    await connection.execute(
        text(f"UPDATE {schema}.user_permissions SET department=ARRAY['MKT','ICE'] WHERE id=1")
    )
    savepoint = await connection.begin_nested()
    rejected = False
    try:
        await migrate(connection, schema, "downgrade")
    except DBAPIError:
        rejected = True
    finally:
        await savepoint.rollback()
    require(rejected, "Downgrade must reject multi-department users")
    require(
        await connection.scalar(
            text(f"SELECT department FROM {schema}.user_permissions WHERE id=1")
        )
        == ["MKT", "ICE"],
        "Failed downgrade discarded departments",
    )
    return [
        "legacy_scalar_null_blank_upgrade",
        "singleton_downgrade",
        "multi_department_downgrade_guard",
    ]


