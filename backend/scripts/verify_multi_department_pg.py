async def main(report_path: Path, import_path: Path | None = None) -> None:
    settings = get_settings()
    require(settings.app_env == "development", "Use the development database profile")
    engine = create_async_engine(
        settings.database_url.get_secret_value(),
        hide_parameters=True,
        connect_args={
            "timeout": 15,
            "server_settings": {"statement_timeout": "20000", "lock_timeout": "3000"},
        },
    )
    schema = "codex_multi_dept_" + uuid4().hex[:12]
    report = {"status": "running", "schema": schema, "checks": [], "external_directory": "fixture"}
    workbook = json.loads(import_path.read_text(encoding="utf-8")) if import_path else None
    if workbook is not None:
        require(not workbook["errors"], "Workbook preview contains errors")
        report["workbook"] = {
            "rows": workbook["rows"],
            "budget": workbook["summary"]["after"],
            "permissions": "synthetic",
        }
    try:
        async with engine.connect() as raw_connection:
            before = await column_type(raw_connection, "data")
            await raw_connection.rollback()
            connection = await raw_connection.execution_options(
                schema_translate_map={"data": schema}
            )
            transaction = await connection.begin()
            try:
                await connection.execute(text(f"CREATE SCHEMA {schema}"))
                report["checks"].extend(await check_migration(connection, schema))
                await connection.run_sync(BaseDO.metadata.create_all)
                report["checks"].extend(await check_api(connection, schema, workbook))
            finally:
                await transaction.rollback()
            remaining = await connection.scalar(
                text("SELECT count(*) FROM pg_namespace WHERE nspname=:schema"), {"schema": schema}
            )
            require(remaining == 0, "Fixture schema was not rolled back")
            require(
                await column_type(connection, "data") == before, "Business department type changed"
            )
            report.update(status="passed", cleanup="rolled_back", business_department_type=before)
    except Exception as error:
        report.update(status="failed", error_type=type(error).__name__)
        if isinstance(error, AssertionError):
            report["error"] = str(error)
        raise
    finally:
        await engine.dispose()
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")
        print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--import-json", type=Path, help="Optional local admin Excel preview JSON")
    arguments = parser.parse_args()
    asyncio.run(main(arguments.report, arguments.import_json))
